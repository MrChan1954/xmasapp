const SEEDS = Array.from({ length: 200 }, (_, index) => index * 2_654_435_761 + 12_345);

test("dashboard spend equals Event Home spend, for both events, at every seed", () => {
  for (const seed of SEEDS) {
    const family = generateFamily(seed);
    for (const eventId of family.events) {
      const card = dashboardCard(family, eventId);
      const home = eventHomeTotals(family, eventId);
      assert.equal(card.spentPennies, home.spentPennies, `spend disagreed for ${eventId} at seed ${seed}`);
      assert.equal(card.budgetPennies, home.budgetPennies, `budget disagreed for ${eventId} at seed ${seed}`);
    }
  }
});

test("the fixture really does exercise the cases that matter", () => {
  // A property test that never hits the interesting rows proves nothing, so
  // assert the generator produces them.
  let archivedWithPurchases = 0;
  let voided = 0;
  let live = 0;
  for (const seed of SEEDS) {
    const family = generateFamily(seed);
    const archived = new Set(family.recipients.filter((row) => !row.active).map((row) => row.id));
    for (const purchase of family.purchases) {
      if (purchase.deleted_at === null) live += 1; else voided += 1;
      if (archived.has(purchase.christmas_recipient_id) && purchase.deleted_at === null) archivedWithPurchases += 1;
    }
  }
  assert.ok(live > 0, "the fixture must contain live purchases");
  assert.ok(voided > 0, "the fixture must contain voided purchases");
  assert.ok(
    archivedWithPurchases > 0,
    "the fixture must contain live purchases for archived recipients — the case that broke the card",
  );
});

test("a second event's purchases never move the first event's card", () => {
  for (const seed of SEEDS.slice(0, 50)) {
    const family = generateFamily(seed);
    const before = dashboardCard(family, "event-a");

    // Everything about event B changes: more recipients, more money.
    const extended = {
      ...family,
      recipients: [
        ...family.recipients,
        { id: "event-b-extra", christmas_event_id: "event-b", budget_pennies: 999_99, active: true },
      ],
      purchases: [
        ...family.purchases,
        { id: "event-b-extra-purchase", christmas_recipient_id: "event-b-extra", actual_price_pennies: 4_242, deleted_at: null },
      ],
    };

    const after = dashboardCard(extended, "event-a");
    assert.deepEqual(after, before, `event B contaminated event A at seed ${seed}`);
    assert.notDeepEqual(
      dashboardCard(extended, "event-b"),
      dashboardCard(family, "event-b"),
      "the change must actually have landed on event B",
    );
  }
});

test("a voided purchase contributes nothing, and archiving a recipient removes their spend from both", () => {
  const family = generateFamily(7);
  const target = family.recipients.find((row) => row.active && row.christmas_event_id === "event-a");
  assert.ok(target);

  // Adding a VOIDED purchase changes neither figure.
  const withVoided = {
    ...family,
    purchases: [...family.purchases, {
      id: "voided-extra",
      christmas_recipient_id: target.id,
      actual_price_pennies: 5_555,
      deleted_at: "2026-12-01T00:00:00Z",
    }],
  };
  assert.deepEqual(dashboardCard(withVoided, "event-a"), dashboardCard(family, "event-a"));
  assert.deepEqual(eventHomeTotals(withVoided, "event-a"), eventHomeTotals(family, "event-a"));

  // Adding a LIVE purchase moves both by exactly the same amount.
  const withLive = {
    ...family,
    purchases: [...family.purchases, {
      id: "live-extra",
      christmas_recipient_id: target.id,
      actual_price_pennies: 5_555,
      deleted_at: null,
    }],
  };
  assert.equal(
    dashboardCard(withLive, "event-a").spentPennies - dashboardCard(family, "event-a").spentPennies,
    5_555,
  );
  assert.equal(
    eventHomeTotals(withLive, "event-a").spentPennies - eventHomeTotals(family, "event-a").spentPennies,
    5_555,
  );

  // Archiving that recipient removes their spend from BOTH, together.
  const archived = {
    ...withLive,
    recipients: withLive.recipients.map((row) => (row.id === target.id ? { ...row, active: false } : row)),
  };
  assert.deepEqual(dashboardCard(archived, "event-a"), eventHomeTotals(archived, "event-a"));
});

