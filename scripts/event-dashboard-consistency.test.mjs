import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import test from "node:test";

/**
 * The dashboard card must agree with the screen it opens.
 *
 * WHY THIS FILE EXISTS
 *   Checkpoint 2 added a second place that reports an event's spend. Two places
 *   computing the same figure is exactly how they end up disagreeing, and a
 *   card that overstates what an event has cost is worse than a card with no
 *   figure at all.
 *
 * NO MAGIC EXPECTED VALUES
 *   Nothing here asserts a particular number of pounds. Every figure is
 *   GENERATED by a seeded pseudo-random fixture and the assertions are
 *   relational: dashboard equals Event Home, event A is unaffected by event B,
 *   a voided purchase counts for nothing, an archived recipient counts for
 *   nothing. The fixture is re-generated across many seeds, so the properties
 *   hold for whatever the live figures happen to be rather than for one
 *   snapshot of them.
 *
 *   In particular: no value in this repository asserts what Christmas 2026 has
 *   actually cost. That is live data, and only the database knows it.
 */

const root = process.cwd();
// Line endings are normalised on the way in. Git stores LF and checks files out
// as CRLF on Windows, so a multi-line pattern written with \n silently stops
// matching a file nobody has edited -- a false failure about the product,
// caused by a checkout setting.
const read = (...parts) => readFileSync(join(root, ...parts), "utf8").replace(/\r\n/gu, "\n");

// ---------------------------------------------------------------------------
// A seeded generator, so a failure is reproducible and no constant is magic
// ---------------------------------------------------------------------------

function makeRandom(seed) {
  let state = seed >>> 0;
  return () => {
    // xorshift32 — small, deterministic, and good enough to shuffle pennies.
    state ^= state << 13; state >>>= 0;
    state ^= state >> 17;
    state ^= state << 5; state >>>= 0;
    return state / 0x1_0000_0000;
  };
}

/**
 * Two events, each with active and archived recipients, live and voided
 * purchases. Amounts and counts all come from the seed.
 */
function generateFamily(seed) {
  const random = makeRandom(seed);
  const between = (low, high) => low + Math.floor(random() * (high - low + 1));

  const events = ["event-a", "event-b"];
  const recipients = [];
  const purchases = [];

  for (const eventId of events) {
    const recipientCount = between(2, 5);
    for (let index = 0; index < recipientCount; index += 1) {
      const recipientId = `${eventId}-recipient-${index}`;
      // At least one archived recipient per event once the count allows it:
      // this is the case that made the dashboard and Event Home disagree.
      const active = index === 0 ? true : between(0, 3) > 0;
      recipients.push({
        id: recipientId,
        christmas_event_id: eventId,
        budget_pennies: between(0, 20_000),
        active,
      });

      for (let purchase = 0; purchase < between(0, 4); purchase += 1) {
        const voided = between(0, 3) === 0;
        purchases.push({
          id: `${recipientId}-purchase-${purchase}`,
          christmas_recipient_id: recipientId,
          actual_price_pennies: between(1, 12_000),
          deleted_at: voided ? "2026-11-11T10:00:00Z" : null,
        });
      }
    }
  }

  return { events, recipients, purchases };
}

// ---------------------------------------------------------------------------
// The two code paths, each mirroring one real implementation
// ---------------------------------------------------------------------------

/**
 * `listEvents` in src/utils/supabase/events-server.ts.
 *
 * Active recipients of the event; live purchases belonging to those recipients.
 */
function dashboardCard(family, eventId) {
  const recipients = family.recipients.filter((row) => row.active);
  const eventByRecipient = new Map(recipients.map((row) => [row.id, row.christmas_event_id]));

  let budgetPennies = 0;
  for (const row of recipients) {
    if (row.christmas_event_id === eventId) budgetPennies += row.budget_pennies;
  }

  let spentPennies = 0;
  for (const purchase of family.purchases) {
    if (purchase.deleted_at !== null) continue;
    if (eventByRecipient.get(purchase.christmas_recipient_id) !== eventId) continue;
    spentPennies += purchase.actual_price_pennies;
  }

  return { budgetPennies, spentPennies };
}

/**
 * Event Home: `FamilyProvider` loads this event's recipients with their live
 * purchase totals, and `useTotals` sums the active ones.
 */
function eventHomeTotals(family, eventId) {
  const recipients = family.recipients.filter((row) => row.christmas_event_id === eventId);

  const spentByRecipient = new Map();
  for (const purchase of family.purchases) {
    if (purchase.deleted_at !== null) continue;
    if (!recipients.some((row) => row.id === purchase.christmas_recipient_id)) continue;
    spentByRecipient.set(
      purchase.christmas_recipient_id,
      (spentByRecipient.get(purchase.christmas_recipient_id) ?? 0) + purchase.actual_price_pennies,
    );
  }

  const people = recipients.map((row) => ({
    active: row.active,
    budgetPennies: row.budget_pennies,
    spentPennies: spentByRecipient.get(row.id) ?? 0,
  }));

  const active = people.filter((person) => person.active);
  return {
    budgetPennies: active.reduce((sum, person) => sum + person.budgetPennies, 0),
    spentPennies: active.reduce((sum, person) => sum + person.spentPennies, 0),
  };
}

