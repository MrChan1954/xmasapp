test("both real implementations still carry the rule these models encode", () => {
  const server = read("src", "utils", "supabase", "events-server.ts");
  // Active recipients only, live purchases only, integer pennies.
  assert.match(server, /\.filter\(\(row\) => row\.active\)/, "the dashboard must drop archived recipients");
  assert.match(server, /\.is\("deleted_at", null\)/, "the dashboard must drop voided purchases");
  assert.match(server, /actual_price_pennies/);
  assert.doesNotMatch(server, /Math\.round|toFixed|parseFloat/, "pennies stay integers");
  // And it says out loud that it has to agree with Event Home.
  assert.match(server, /THE CARD MUST AGREE WITH THE SCREEN IT OPENS/);

  const familyContext = read("src", "app", "family-context.tsx");
  assert.match(familyContext, /\.is\("deleted_at", null\)/, "Event Home must drop voided purchases");
  assert.match(
    familyContext,
    /const active = people\.filter\(\(person\) => person\.active\)/,
    "useTotals must sum active recipients only",
  );

  // Neither path invents a figure: no financial engine is involved in either.
  for (const source of [server, read("src", "app", "events-dashboard.tsx")]) {
    assert.doesNotMatch(source, /calculateNetOwedBalances|splitEvenly|responsibility/i);
  }
});

test("no test or screen asserts what Christmas has actually cost", () => {
  // The £95 in the Checkpoint 1 preflight was a value invented for a disposable
  // in-memory fixture. It is not, and must never become, an expectation about
  // the live database.
  const dashboard = read("src", "app", "events-dashboard.tsx");
  const server = read("src", "utils", "supabase", "events-server.ts");
  for (const source of [dashboard, server]) {
    assert.doesNotMatch(source, /\b9500\b|\b9_500\b|£95\b/, "no fixture figure may appear in application code");
  }

  // Where fixture figures DO appear, they are invented inside the file that
  // asserts them — a closed loop, not a reading taken from the live database.
  const scoping = read("scripts", "event-scoping.test.mjs");
  assert.match(scoping, /9_500/, "the Checkpoint 1 suite does assert its own totals");
  assert.match(
    scoping,
    /INVENTED, NOT OBSERVED/,
    "and it must say plainly that those totals are invented",
  );
  assert.match(scoping, /familyFixture\(\)/, "its figures come from a fixture defined in the same file");

  // Nothing in this suite states an expected pound value at all: every
  // assertion above is relational.
  const self = read("scripts", "event-dashboard-consistency.test.mjs");
  // Only positive expectations count: a `doesNotMatch` guard naturally names
  // the figure it is banning.
  const expectations = self.split("\n").filter((line) => /assert\.(equal|deepEqual|match)\b/u.test(line));
  assert.ok(expectations.length > 0);
  assert.equal(
    expectations.filter((line) => /£/u.test(line)).length,
    0,
    "this suite must not assert a pound figure",
  );
});
